"""
Automated DOCX Text-Extraction Round-Trip Test (Milestone 6)
------------------------------------------------------------
Inspects and tests through the existing Python parser interface:
  1. Opens the temporary DOCX file generated by frontend/test_docx_export.js.
  2. Passes the file bytes to parse_resume_bytes().
  3. Verifies normalized textual content preservation and order:
     - Documented transformations: bullet markers (- , * , etc.) become native
       Word bullets (and thus are stripped from the paragraph text by docx).
     - Documented transformations: repeated blank lines collapse.
     - Preserves all factual content, numbers, words, and relative ordering.
  4. Note: This automated test verifies textual content extraction and structural order,
     NOT pixel-perfect visual styling.
"""

import sys
import os
import tempfile
import unittest

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from services.parser import parse_resume_bytes


class TestDocxRoundTrip(unittest.TestCase):

    def test_docx_text_extraction_roundtrip(self):
        temp_docx_path = os.path.join(tempfile.gettempdir(), "careerpilot_test_generated.docx")
        
        self.assertTrue(
            os.path.exists(temp_docx_path),
            f"Expected temporary DOCX at {temp_docx_path}. Run frontend/test_docx_export.js first.",
        )

        try:
            # 1. Read through standard file interface
            with open(temp_docx_path, "rb") as f:
                file_bytes = f.read()

            self.assertGreater(len(file_bytes), 0, "DOCX file must not be empty.")

            # 2. Extract using existing Milestone 2 parser
            result = parse_resume_bytes(file_bytes)
            self.assertEqual(result["file_type"], "Word document")

            extracted_text = result["extracted_text"]
            self.assertGreater(len(extracted_text), 0, "Extracted text must not be empty.")

            # 3. Normalized content preservation checks
            # Header content
            self.assertIn("RAJ BIND", extracted_text)
            self.assertIn("DevOps & Cloud Operations | AWS | Linux | Docker | Kubernetes | CI/CD", extracted_text)
            self.assertIn("Mumbai, Maharashtra, India | [GitHub URL]", extracted_text)

            # Section titles
            self.assertIn("PROFESSIONAL SUMMARY", extracted_text)
            self.assertIn("CAREER HIGHLIGHTS", extracted_text)
            self.assertIn("TECHNICAL SKILLS", extracted_text)
            self.assertIn("PROJECTS", extracted_text)
            self.assertIn("WORK EXPERIENCE", extracted_text)
            self.assertIn("EDUCATION", extracted_text)

            # Technical skills categories and contents
            self.assertIn("Cloud (AWS): EC2, IAM, VPC, Security Groups, S3, CloudWatch, CloudTrail", extracted_text)
            self.assertIn("Containers & Orchestration: Docker, Docker Compose, Dockerfile, Kubernetes", extracted_text)

            # Projects section content
            self.assertIn("Cloud Infrastructure Automation Pipeline", extracted_text)
            self.assertIn("Tech Stack: AWS, Terraform, GitHub Actions, Docker", extracted_text)
            self.assertIn("Architected an automated multi-region cloud deployment framework.", extracted_text)
            self.assertIn("Automated VPC provisioning and IAM policy enforcement.", extracted_text)

            # Bullet points (checking that textual content survived after marker conversion to native bullets)
            self.assertIn("Designed and deployed containerized microservices on AWS EKS.", extracted_text)
            self.assertIn("Maintained PostgreSQL databases and Redis caching layers.", extracted_text)
            self.assertIn("Automated deployment verification using Python test suites.", extracted_text)

            # Education content
            self.assertIn("Bachelor of Science in Information Technology", extracted_text)

            # 4. Order preservation check
            idx_name = extracted_text.index("RAJ BIND")
            idx_summary = extracted_text.index("PROFESSIONAL SUMMARY")
            idx_highlights = extracted_text.index("CAREER HIGHLIGHTS")
            idx_skills = extracted_text.index("TECHNICAL SKILLS")
            idx_projects = extracted_text.index("PROJECTS")
            idx_experience = extracted_text.index("WORK EXPERIENCE")
            idx_education = extracted_text.index("EDUCATION")

            self.assertTrue(
                idx_name < idx_summary < idx_highlights < idx_skills < idx_projects < idx_experience < idx_education,
                "Relative section order must be preserved exactly.",
            )

            print("✓ Text-extraction round-trip verified: Normalized content and order preserved across parser round-trip.")
        finally:
            # Safe cleanup of temporary file
            if os.path.exists(temp_docx_path):
                os.remove(temp_docx_path)


if __name__ == "__main__":
    unittest.main()
